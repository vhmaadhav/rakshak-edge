#!/usr/bin/env python3
"""Build a Kaggle job kernel, maadhavvh/rakshak-<job>, into kaggle/out/<job>/kernel/.

Usage:
  python3 kaggle/build_kernel.py --job smoke
  python3 kaggle/build_kernel.py --job train --gpu t4 --internet --datasets maadhavvh/rakshak-data

Writes kernel-metadata.json and run.py. Nothing is pushed and no computation runs here.

--platform colab writes only run.py, into colab/out/<job>/kernel/, for colab/launch.sh (it uploads
run.py to /content/rakshak_run.py, and colab/remote_start_job.py starts it detached).
The runner then works in /content/out, reads data from /content/rakshak-data
and sends the completion as rakshak-colab-<job>. Colab has internet, so the notify topic is always
set; the accelerator comes from colab new --gpu, so --gpu, --datasets and --models are refused.

run.py is generated from RUN_TEMPLATE below and embeds:
- the bundle: the working-tree files of src/rakshak/, kaggle/jobs/_common.py and
  kaggle/jobs/<job>.py, as a gzip tar in base64. The kernel runs the code as it was on disk at build
  time;
- the HEAD commit (GIT_SHA, empty while HEAD is unborn), a DIRTY flag, and TREE_SHA256, the sha256
  over the bundled files, so a run can be matched to the exact code even before the first commit;
- the build time, the job name, the pinned pip set (kaggle/requirements-kaggle.txt, used only with
  internet) and the notify URL (only with --internet).

The notify topic comes from RAKSHAK_NTFY_TOPIC or the first line of ~/.config/rakshak/ntfy_topic.
The file is created on the first build (directory mode 700, file mode 600) with a random topic. The
topic is never printed or committed. kaggle/out/ is gitignored.

Accelerator: --gpu sets enable_gpu true and machine_shape in kernel-metadata.json. The Kaggle CLI
2.2.4 accepts only "NvidiaTeslaT4" and "NvidiaTeslaP100" (as listed in kagglesdk), so --gpu t4
(default) or --gpu p100.

Run name: --run-name NAME (1 to 20 characters of a-z, 0-9 and hyphen) builds another run of the same
job as its own kernel: maadhavvh/rakshak-<job>-NAME, output kaggle/out/<job>-NAME/kernel/, and the
notification prefix rakshak-<job>-NAME. Without it the output is unchanged. Kaggle only.
"""

