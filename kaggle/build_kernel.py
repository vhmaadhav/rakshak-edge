def git(*args: str) -> str:
    proc = subprocess.run(['git', '-C', str(REPO), *args], capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f'build: git {args[0]} failed: {proc.stderr.strip()}')
    return proc.stdout


def head_sha() -> str:
    """HEAD commit, or '' while the repository has no commits yet."""
    proc = subprocess.run(['git', '-C', str(REPO), 'rev-parse', '--verify', '-q', 'HEAD'],
                          capture_output=True, text=True)
    return proc.stdout.strip() if proc.returncode == 0 else ''


def bundle_names(job: str) -> list[str]:
    """Relative paths of the bundle, from git's view of the working tree (ignored files
    excluded)."""
    if not (REPO / PACKAGE_DIR / '__init__.py').is_file():
        sys.exit(f'build: {PACKAGE_DIR}/__init__.py does not exist yet; the rakshak package is '
                 'needed before a kernel can be built. Nothing was written.')
    job_rel = f'kaggle/jobs/{job}.py'
    if not (REPO / job_rel).is_file():
        sys.exit(f'build: {job_rel} does not exist; write the job file first. Nothing was written.')
    listed = git('ls-files', '-z', '--cached', '--others', '--exclude-standard', '--',
                 PACKAGE_DIR, SHARED_FILE, job_rel)
    names = set()
    for rel in listed.split('\0'):
        if not rel or SKIP_PARTS & set(Path(rel).parts) or rel.endswith('.pyc'):
            continue
        if (REPO / rel).is_symlink():
            sys.exit(f'build: symlinks cannot be bundled: {rel}')
        names.add(rel)
    return sorted(names)


def notify_url(internet: bool) -> tuple[str, str]:
    """(url, where the topic came from). The topic itself is never printed."""
    if not internet:
        return '', 'disabled (no internet)'
    topic = os.environ.get('RAKSHAK_NTFY_TOPIC', '').strip()
    source = 'RAKSHAK_NTFY_TOPIC'
    if not topic and TOPIC_FILE.exists():
        lines = TOPIC_FILE.read_text().splitlines()
        topic = lines[0].strip() if lines else ''
        source = f'{TOPIC_FILE} (existing)'
    if not topic:
        CONFIG_DIR.mkdir(parents=True, exist_ok=True)
        os.chmod(CONFIG_DIR, 0o700)
        topic = 'rakshak-' + secrets.token_hex(16)
        fd = os.open(TOPIC_FILE, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, 'w') as fh:
            fh.write(topic + '\n')
        os.chmod(TOPIC_FILE, 0o600)
        source = f'{TOPIC_FILE} (created)'
    if not TOPIC_RE.fullmatch(topic):
        sys.exit('build: the ntfy topic must be 8 to 64 letters, digits, "-" or "_"')
    return f'https://ntfy.sh/{topic}', source


def pinned_requirements() -> list[str]:
    if not PINS_FILE.is_file():
        sys.exit(f'build: {PINS_FILE} is missing')
    lines = []
    for raw in PINS_FILE.read_text().splitlines():
        line = raw.strip()
        if line and not line.startswith('#'):
            if '==' not in line.split(';', 1)[0]:
                sys.exit(f'build: every line in {PINS_FILE.name} must pin with ==: {line}')
            lines.append(line)
    return lines


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--job', required=True,
                        help='job name: kaggle/jobs/<job>.py, kernel maadhavvh/rakshak-<job>')
    parser.add_argument('--platform', choices=('kaggle', 'colab'), default='kaggle',
                        help='kaggle (default): kernel metadata in kaggle/out/; colab: run.py '
                             'only, in colab/out/ (see colab/launch.sh)')
    parser.add_argument('--gpu', nargs='?', const='t4', default=None, choices=sorted(GPU_SHAPES),
                        help='enable a GPU: t4 (default when given without a value) or p100')
    parser.add_argument('--internet', action='store_true',
                        help='enable internet: needed for the pinned pip install and the '
                             'completion notification')
    parser.add_argument('--datasets', nargs='*', default=[], metavar='OWNER/SLUG',
                        help='Kaggle datasets to attach, e.g. maadhavvh/rakshak-data')
    parser.add_argument('--models', nargs='*', default=[], metavar='OWNER/MODEL/...',
                        help='Kaggle model sources to attach')
    parser.add_argument('--kernels', nargs='*', default=[], metavar='OWNER/SLUG',
                        help='completed Kaggle kernel outputs to attach privately')
    parser.add_argument('--job-args', default='', metavar='"FLAGS"',
                        help='flags for the job, passed to run(ctx) as ctx.argv, e.g. "--hpo 8"')
    parser.add_argument('--wall-limit-h', type=float, default=0.0, metavar='HOURS',
                        help='hard wall-clock limit for the runner: past it the run is recorded '
                             'as error (WallClockLimit) and the completion is sent. 0 (default): '
                             'none. colab/launch.sh passes its budget plus a margin.')
    parser.add_argument('--run-name', default=None, metavar='NAME',
                        help='another run of the same job as its own Kaggle kernel: '
                             'maadhavvh/rakshak-<job>-NAME, output kaggle/out/<job>-NAME/. '
                             'NAME: 1 to 20 characters of a-z, 0-9 and hyphen. Kaggle only.')
    parser.add_argument('--require-clean', action='store_true',
                        help='refuse to build while the bundled paths have uncommitted or '
                             'untracked changes')
    args = parser.parse_args(argv)
    if args.wall_limit_h < 0:
        parser.error('--wall-limit-h must not be negative')

    job = args.job
    if not JOB_RE.fullmatch(job):
        parser.error('the job name must start with a letter and use only lowercase '
                     'letters, digits, "_" and "-"')
    slug = job.replace('_', '-')
    for dataset in args.datasets:
        if not DATASET_RE.fullmatch(dataset):
            parser.error(f'dataset must look like OWNER/SLUG: {dataset}')
    for model in args.models:
        if not all(part for part in model.split('/')) or '/' not in model:
            parser.error(f'model must look like OWNER/MODEL/...: {model}')
    for kernel in args.kernels:
        if not DATASET_RE.fullmatch(kernel):
            parser.error(f'kernel must look like OWNER/SLUG: {kernel}')
    colab = args.platform == 'colab'
    if colab:
        for flag, given in (('--gpu', args.gpu), ('--datasets', args.datasets),
                            ('--models', args.models), ('--kernels', args.kernels)):
            if given:
                parser.error(f'{flag} is a Kaggle option; with --platform colab the accelerator '
                             'comes from colab new --gpu')

    suffix = ''
    if args.run_name is not None:
        if colab:
            parser.error('--run-name is a Kaggle option: colab runs one kernel per job')
        if not RUN_NAME_RE.fullmatch(args.run_name):
            parser.error('--run-name must be 1 to 20 characters of a-z, 0-9 and hyphen: '
                         f'{args.run_name!r}')
        suffix = '-' + args.run_name
        slug = slug + suffix

    job_argv = shlex.split(args.job_args)
    names = bundle_names(job)
    dirty = git('status', '--porcelain', '--untracked-files=normal', '--', PACKAGE_DIR, SHARED_FILE,
                f'kaggle/jobs/{job}.py').strip()
    if dirty and args.require_clean:
        sys.exit('build: the bundled paths have uncommitted or untracked changes '
                 '(--require-clean):\n' + dirty)

    files = {rel: (REPO / rel).read_bytes() for rel in names}
    tree = hashlib.sha256()
    for rel in names:
        tree.update(rel.encode('utf-8') + b'\0' + hashlib.sha256(files[rel]).digest())
    tree_sha256 = tree.hexdigest()

    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode='w:gz') as archive:
        for rel in names:
            info = tarfile.TarInfo(rel)
            info.size = len(files[rel])
            info.mtime = 0
            info.mode = 0o644
            archive.addfile(info, io.BytesIO(files[rel]))
    bundle = buffer.getvalue()
    if len(bundle) > MAX_BUNDLE_BYTES:
        sys.exit(f'build: bundle is {len(bundle)} bytes, above the {MAX_BUNDLE_BYTES} byte limit')

    sha = head_sha()
    label = sha[:12] if sha else 'no-commit'
    internet = colab or bool(args.internet)
    url, source = notify_url(internet)
    pins = pinned_requirements()
    built_at = datetime.now(UTC).strftime('%Y-%m-%dT%H:%M:%SZ')
    gpu_shape = GPU_SHAPES[args.gpu] if args.gpu else None

    replacements = {
        '__JOB__': json.dumps(job),
        '__PLATFORM__': json.dumps(args.platform),
        '__GIT_SHA__': json.dumps(sha),
        '__GIT_LABEL__': json.dumps(label),
        '__DIRTY__': repr(bool(dirty)),
        '__TREE_SHA256__': json.dumps(tree_sha256),
        '__BUILT_AT__': json.dumps(built_at),
        '__ENABLE_INTERNET__': repr(internet),
        '__NOTIFY_URL__': json.dumps(url),
        '__PIP_PINS__': json.dumps(pins),
        '__BUNDLE_B64__': json.dumps(base64.b64encode(bundle).decode('ascii')),
        '__JOB_ARGV__': repr(job_argv),
        '__WALL_LIMIT_S__': repr(round(args.wall_limit_h * 3600, 3)),
        '__RUN_SUFFIX__': f' + {json.dumps(suffix)}' if suffix else '',
    }
    text = RUN_TEMPLATE
    for key, value in replacements.items():
        if text.count(key) != 1:
            sys.exit(f'build: template placeholder {key} must occur exactly once')
        text = text.replace(key, value)
    compile(text, 'run.py', 'exec')  # syntax check before anything is written

    out_dir = (COLAB_OUT_ROOT if colab else OUT_ROOT) / (job + suffix) / 'kernel'
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / 'run.py').write_text(text)
    metadata = {
        'id': f'{OWNER}/rakshak-{slug}',
        'title': f'rakshak {slug}',
        'code_file': 'run.py',
        'language': 'python',
        'kernel_type': 'script',
        'is_private': True,
        'enable_gpu': gpu_shape is not None,
        'enable_tpu': False,
        'enable_internet': internet,
        'dataset_sources': list(args.datasets),
        'competition_sources': [],
        'kernel_sources': list(args.kernels),
        'model_sources': list(args.models),
        'keywords': [],
    }
    if gpu_shape:
        metadata['machine_shape'] = gpu_shape
    if colab:
        print(f'kernel: rakshak-colab-{slug} (run.py only; colab/launch.sh runs it)')
    else:
        (out_dir / 'kernel-metadata.json').write_text(json.dumps(metadata, indent=2) + '\n')
        print(f"kernel: {metadata['id']}")
    print(f'job: kaggle/jobs/{job}.py')
    if suffix:
        print(f'run name: {args.run_name} (notification prefix rakshak-{slug})')
    print(f'git HEAD: {label}; bundled paths '
          + ('DIRTY (uncommitted changes bundled)' if dirty else 'clean'))
    print(f'tree sha256: {tree_sha256[:12]} ({len(names)} files, {len(bundle)} bytes gzip)')
    accelerator = 'set by colab new --gpu' if colab else (gpu_shape or 'CPU')
    print(f"accelerator: {accelerator}; internet: {'on' if internet else 'off'}")
    print(f"datasets: {', '.join(args.datasets) or 'none'}; "
          f"models: {', '.join(args.models) or 'none'}")
    print(f'pinned pip lines: {len(pins)}'
          + ('' if internet else ' (not installed: internet is off)'))
    print(f'notify topic: from {source}; value not shown')
    print(f'wrote {out_dir / "run.py"}' + ('' if colab else ' and kernel-metadata.json'))


