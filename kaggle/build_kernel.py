        _cancel_watchdog.set()
        finalize()
        log(f"done: status={STATE['status']} total_s={STATE.get('total_s')}")
        if _outcome_by == 'watchdog':
            _watchdog_thread.join()  # the watchdog ends the process with os._exit
        _log.close()


