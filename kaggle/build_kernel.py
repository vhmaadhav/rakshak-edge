def log(msg):
    line = str(msg)
    print(line, flush=True)
    if _log is not None:
        _log.write(line + '\n')
        _log.flush()


def save():
    STATE['total_s'] = round(time.time() - T0, 1)
    tmp = RESULTS.with_name(RESULTS.name + '.tmp')
    tmp.write_text(json.dumps(STATE, indent=2, default=str) + '\n')
    tmp.replace(RESULTS)


def gpu_report():
    """GPU names and memory from nvidia-smi, or None when there is no GPU. torch is not imported
    here: the job imports it (kaggle/jobs/_common.py env_report does the torch check)."""
    try:
        proc = subprocess.run(['nvidia-smi', '--query-gpu=name,memory.total',
                               '--format=csv,noheader'],
                              capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None
    return [line.strip() for line in proc.stdout.splitlines() if line.strip()] or None


def environment():
    try:
        cpus = len(os.sched_getaffinity(0))
    except AttributeError:
        cpus = os.cpu_count()
    ram_gb = None
    try:
        for line in Path('/proc/meminfo').read_text().splitlines():
            if line.startswith('MemTotal:'):
                ram_gb = round(int(line.split()[1]) / 1024 / 1024, 1)
    except OSError:
        pass
    info = {
        'python': platform.python_version(),
        'executable': sys.executable,
        'platform': platform.platform(),
        'cpus': cpus,
        'ram_gb': ram_gb,
        'gpu': gpu_report(),
        'internet': bool(ENABLE_INTERNET),
    }
    STATE['environment'] = info
    log('environment: ' + json.dumps(info))


def install_pins():
    if not PIP_PINS:
        return
    if not ENABLE_INTERNET:
        STATE['pip'] = 'skipped (kernel has no internet); preinstalled packages are used'
        log('pip: ' + STATE['pip'])
        return
    req = SCRATCH / 'requirements-kaggle.txt'
    req.write_text('\n'.join(PIP_PINS) + '\n')
    proc = subprocess.run([sys.executable, '-m', 'pip', 'install', '--quiet',
                           '--disable-pip-version-check',
                           '-r', str(req)], capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError('pinned pip install failed: ' + proc.stderr.strip()[-400:])
    STATE['pip'] = {'pins': len(PIP_PINS), 'status': 'installed'}
    log(f'pip: installed {len(PIP_PINS)} pinned requirement lines')


def unpack():
    if REPO.exists():
        shutil.rmtree(REPO)
    REPO.mkdir(parents=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE_B64)), mode='r:gz') as tar:
        tar.extractall(REPO, filter='data')
    for need in ('src/rakshak/__init__.py', 'kaggle/jobs/_common.py', f'kaggle/jobs/{JOB}.py'):
        if not (REPO / need).is_file():
            raise RuntimeError(f'the bundle lacks {need}')
    log(f'unpacked the bundle into {REPO}')


def load_job():
    path = REPO / 'kaggle' / 'jobs' / f'{JOB}.py'
    sys.path[:0] = [str(REPO / 'src'), str(REPO / 'kaggle' / 'jobs')]
    name = f'rakshak_job_{JOB}'
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    # Register before exec: @dataclass (and pickle) look the module up in sys.modules while the
    # class body runs, so an unregistered module crashes with AttributeError on NoneType.
    sys.modules[name] = module
    spec.loader.exec_module(module)
    if not callable(getattr(module, 'run', None)):
        raise RuntimeError(f'{path.name} defines no run(ctx)')
    return module


class Context:
    """What a job's run(ctx) gets. Set ctx.results['summary'] to a short line for the
    notification."""

    def __init__(self):
        self.job = JOB
        self.repo = REPO
        self.src = REPO / 'src'
        self.work = WORK
        self.input_root = INPUT_ROOT
        self.scratch = SCRATCH / 'scratch'
        self.scratch.mkdir(parents=True, exist_ok=True)
        self.python = sys.executable
        self.results = STATE
        self.argv = list(JOB_ARGV)

    def log(self, msg):
        log(msg)

    def save(self):
        save()


def notify():
    """One line: rakshak-<job> ok|fail git=<sha12> tree=<hash12>[+dirty] <summary>. Never raises."""
    if not NOTIFY_URL:
        log('notify: skipped (kernel has no internet)')
        return
    status = STATE['status'] if STATE['status'] in ('ok', 'partial') else 'fail'
    summary = STATE.get('summary') or ''
    if STATE.get('error'):
        summary = (str(STATE['error']).split(':', 1)[0] + ' ' + summary).strip()
    tree = TREE_SHA256[:12] + ('+dirty' if DIRTY else '')
    line = f'rakshak-{SLUG} {status} git={GIT_LABEL} tree={tree} {summary}'
    line = ' '.join(line.split())[:300]
    try:
        req = urllib.request.Request(NOTIFY_URL, data=line.encode('utf-8'), method='POST',
                                     headers={'Content-Type': 'text/plain; charset=utf-8',
                                              'Title': f'rakshak {JOB}',
                                              'Tags': ('white_check_mark' if status == 'ok'
                                                       else 'warning')})
        urllib.request.urlopen(req, timeout=10).read()
        log('notify: sent')
    except Exception as exc:  # the URL is never logged; the job result is unaffected
        log(f'notify: failed ({type(exc).__name__})')


_outcome_lock = threading.Lock()
_outcome_by = None               # 'main' or 'watchdog': whichever side set the outcome first
_cancel_watchdog = threading.Event()
_watchdog_thread = None


def set_outcome(status, error=None, by='main'):
    """Record the outcome once. False when the other side (the job or the watchdog) already did,
    so a run is never reported twice."""
    global _outcome_by
    with _outcome_lock:
        if _outcome_by is not None:
            return False
        _outcome_by = by
        STATE['status'] = status
        if error is not None:
            STATE['error'] = error
        return True


def write_and_notify():
    try:
        STATE['finished_utc'] = utc()
        save()
    except Exception as exc:
        log(f'results.json write failed ({type(exc).__name__})')
    shutil.rmtree(REPO, ignore_errors=True)
    notify()


def watchdog():
    """The hard wall-clock limit (colab/launch.sh passes budget + margin). If the job has not ended
    by then, the run is recorded as error, the completion line is sent and the process exits, so a
    hung run still reports. A run that ends earlier cancels this thread."""
    if _cancel_watchdog.wait(WALL_LIMIT_S):
        return
    if not set_outcome('error', f'WallClockLimit: no end within {WALL_LIMIT_S} s', by='watchdog'):
        return
    log('ERROR ' + STATE['error'])
    write_and_notify()
    os._exit(1)


def finalize():
    if _outcome_by == 'main':
        write_and_notify()


