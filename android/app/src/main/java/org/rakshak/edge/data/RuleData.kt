package org.rakshak.edge.data

import org.json.JSONObject

/** One curated brand: its aliases in messages, host labels, and official registered domains. */
data class Brand(
    val name: String,
    val aliases: List<String>,
    val hostAliases: List<String>,
    val domains: List<String>,
)

/** detect_lang word sets and constants, exported from datasets/lang.py. */
data class LangLexicon(
    val hinglishStrong: Set<String>,
    val hinglishWeak: Set<String>,
    val english: Set<String>,
    val minHinglishHits: Int,
    val hinglishRatio: Double,
)

/**
 * Data files the rules read, as shipped in app/src/main/assets/rakshak/ (generated by
 * android/tools/export_assets.py from the Python package).
 *
 * [reader] returns the text of one asset by file name. The activity sets it from AssetManager;
 * the JVM unit tests point it at the source folder.
 */
object RuleData {
    @Volatile
    var reader: (String) -> String = { name -> error("RuleData.reader not set (asked for $name)") }

    /** Brand table. Brand order follows JSONObject's map order, which the rules do not depend on. */
    val brands: Map<String, Brand> by lazy {
        val root = JSONObject(reader("brands.json")).getJSONObject("brands")
        val out = LinkedHashMap<String, Brand>()
        for (name in root.keys()) {
            val b = root.getJSONObject(name)
            out[name] = Brand(
                name = name,
                aliases = b.getJSONArray("aliases").strings(),
                hostAliases = b.getJSONArray("host_aliases").strings(),
                domains = b.getJSONArray("domains").strings(),
            )
        }
        out
    }

    /** ICANN public suffix rules, one per line (wildcards "*.x" and exceptions "!x.y" kept). */
    val suffixRules: Set<String> by lazy {
        reader("public_suffix_icann.txt").lineSequence()
            .map { it.trim().lowercase() }
            .filter { it.isNotEmpty() && !it.startsWith("//") }
            .toHashSet()
    }

    /** ela_lexicon.json: per language ("en", "hinglish"), per evidence type, keyword list. */
    val pointLexicon: Map<String, Map<String, List<String>>> by lazy {
        val root = JSONObject(reader("ela_lexicon.json"))
        mapOf("en" to root.getJSONObject("en").toStringListMap(),
            "hinglish" to root.getJSONObject("hinglish").toStringListMap())
    }

    val langLexicon: LangLexicon by lazy {
        val root = JSONObject(reader("lang_lexicon.json"))
        LangLexicon(
            hinglishStrong = root.getJSONArray("hinglish_strong").strings().toHashSet(),
            hinglishWeak = root.getJSONArray("hinglish_weak").strings().toHashSet(),
            english = root.getJSONArray("english").strings().toHashSet(),
            minHinglishHits = root.getInt("min_hinglish_hits"),
            hinglishRatio = root.getDouble("hinglish_ratio"),
        )
    }

    val llamaLicense: String by lazy { reader("llama3_2_LICENSE.txt") }
}

private fun org.json.JSONArray.strings(): List<String> = List(length()) { getString(it) }

private fun JSONObject.toStringListMap(): Map<String, List<String>> {
    val out = LinkedHashMap<String, List<String>>()
    for (key in keys()) out[key] = getJSONArray(key).strings()
    return out
}
